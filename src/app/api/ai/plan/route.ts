import { NextResponse } from "next/server";
import { z } from "zod";
import { addDays } from "date-fns";
import { requireUser } from "@/lib/require-user";
import { getAIProvider, requestStructuredSuggestion } from "@/lib/ai/provider";
import { consumeAIRequest } from "@/lib/ai/rate-limit";
import { planWork } from "@/lib/scheduling";
const inputSchema = z.object({
  prompt: z.string().max(2000).optional(),
  allowExternalProvider: z.boolean().optional(),
});
export async function GET() {
  const auth = await requireUser();
  if (!auth.ok) return auth.response;
  return NextResponse.json({
    configured: getAIProvider().configured,
    provider: getAIProvider().name,
  });
}
export async function POST(request: Request) {
  const auth = await requireUser();
  if (!auth.ok) return auth.response;
  if (!consumeAIRequest(auth.user.id))
    return NextResponse.json(
      { error: "AI suggestion limit reached. Try again later." },
      { status: 429 },
    );
  const rawBody = await request.text();
  if (rawBody.length > 10_000)
    return NextResponse.json(
      { error: "Planner request is too large" },
      { status: 413 },
    );
  const c = auth.supabase;
  const body = inputSchema.safeParse(
    (() => {
      try {
        return JSON.parse(rawBody);
      } catch {
        return null;
      }
    })(),
  );
  if (!body.success)
    return NextResponse.json(
      { error: "Invalid planner prompt" },
      { status: 400 },
    );
  const [
    { data: tasks, error: te },
    { data: events, error: ee },
    { data: sessions, error: se },
    { data: prefs },
  ] = await Promise.all([
    c
      .from("tasks")
      .select("id,title,due_at,priority,estimated_minutes,status")
      .neq("status", "completed")
      .order("due_at")
      .limit(200),
    c
      .from("calendar_events")
      .select("starts_at,ends_at")
      .gte("ends_at", new Date().toISOString())
      .lte("starts_at", addDays(new Date(), 8).toISOString())
      .order("starts_at")
      .limit(200),
    c
      .from("scheduled_work_sessions")
      .select("starts_at,ends_at")
      .eq("status", "planned")
      .gte("ends_at", new Date().toISOString())
      .lte("starts_at", addDays(new Date(), 8).toISOString())
      .order("starts_at")
      .limit(200),
    c
      .from("user_preferences")
      .select("workday_start,workday_end,timezone")
      .maybeSingle(),
  ]);
  if (te || ee || se)
    return NextResponse.json(
      { error: "Could not load the data needed for a plan" },
      { status: 500 },
    );
  const timeOfDay = (value: string) => {
    const [hour, minute] = value.split(":").map(Number);
    return hour + (minute || 0) / 60;
  };
  const startHour = timeOfDay(String(prefs?.workday_start || "09:00"));
  const endHour = timeOfDay(String(prefs?.workday_end || "17:00"));
  const slots = planWork(
    (tasks || []).map((t) => ({
      id: t.id,
      title: t.title,
      dueAt: t.due_at,
      priority: t.priority,
      minutes: t.estimated_minutes || 60,
    })),
    [
      ...(events || []).map((e) => ({
        start: new Date(e.starts_at),
        end: new Date(e.ends_at),
      })),
      ...(sessions || []).map((s) => ({
        start: new Date(s.starts_at),
        end: new Date(s.ends_at),
      })),
    ],
    new Date(),
    addDays(new Date(), 8),
    startHour,
    endHour,
    prefs?.timezone || "UTC",
  );
  let explanation =
    "Plan generated by Daymark’s on-device scheduling rules. Sessions are split into focused blocks, fit around existing events, and ordered by deadline and priority.";
  let provider = "deterministic";
  const aiProvider = getAIProvider();
  if (body.data.allowExternalProvider === true && aiProvider.configured) {
    const response = await requestStructuredSuggestion(
      "Explain the deterministic proposed work schedule in concise, plain language. Do not modify, rearrange, or invent any tasks, dates, or commitments. Return a JSON object with a single string field named explanation.",
      {
        request: body.data.prompt || "Make a realistic plan for this week.",
        timezone: prefs?.timezone,
        tasks: (tasks || []).slice(0, 40).map((t) => ({
          title: String(t.title).slice(0, 180),
          dueAt: t.due_at,
          priority: t.priority,
          minutes: t.estimated_minutes || 60,
        })),
        busy: (events || []).slice(0, 60),
        proposed: slots.slice(0, 40).map((s) => ({
          title: s.title.slice(0, 180),
          start: s.start.toISOString(),
          end: s.end.toISOString(),
        })),
      },
      z.object({ explanation: z.string().trim().min(1).max(1200) }),
    );
    if (response) {
      explanation = z
        .object({ explanation: z.string().max(1200) })
        .parse(response.value).explanation;
      provider = response.provider;
    } else {
      explanation +=
        " The configured provider was unavailable or returned an invalid response, so this explanation uses Daymark’s deterministic scheduler.";
    }
  }
  return NextResponse.json({
    slots: slots.map((s) => ({
      taskId: s.taskId,
      title: s.title,
      start: s.start.toISOString(),
      end: s.end.toISOString(),
    })),
    explanation,
    provider,
    configured: aiProvider.configured,
  });
}
