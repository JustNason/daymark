import { NextResponse } from "next/server";
import { z } from "zod";
import { addDays } from "date-fns";
import { createClient } from "@/lib/supabase/server";
import { planWork } from "@/lib/scheduling";
const inputSchema = z.object({ prompt: z.string().max(2000).optional() });
export async function POST(request: Request) {
  const c = await createClient();
  if (!c)
    return NextResponse.json(
      { error: "Supabase is not configured" },
      { status: 503 },
    );
  const {
    data: { user },
  } = await c.auth.getUser();
  if (!user)
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  const body = inputSchema.safeParse(await request.json().catch(() => ({})));
  if (!body.success)
    return NextResponse.json(
      { error: "Invalid planner prompt" },
      { status: 400 },
    );
  const [
    { data: tasks, error: te },
    { data: events, error: ee },
    { data: sessions, error: se },
    { data: prefs },
  ] = await Promise.all([
    c
      .from("tasks")
      .select("id,title,due_at,priority,estimated_minutes,status")
      .neq("status", "completed")
      .order("due_at")
      .limit(200),
    c
      .from("calendar_events")
      .select("starts_at,ends_at")
      .gte("ends_at", new Date().toISOString())
      .lte("starts_at", addDays(new Date(), 8).toISOString())
      .order("starts_at")
      .limit(200),
    c
      .from("scheduled_work_sessions")
      .select("starts_at,ends_at")
      .eq("status", "planned")
      .gte("ends_at", new Date().toISOString())
      .lte("starts_at", addDays(new Date(), 8).toISOString())
      .order("starts_at")
      .limit(200),
    c
      .from("user_preferences")
      .select("workday_start,workday_end,timezone")
      .maybeSingle(),
  ]);
  if (te || ee || se)
    return NextResponse.json(
      { error: te?.message || ee?.message || se?.message },
      { status: 500 },
    );
  const timeOfDay = (value: string) => {
    const [hour, minute] = value.split(":").map(Number);
    return hour + (minute || 0) / 60;
  };
  const startHour = timeOfDay(String(prefs?.workday_start || "09:00"));
  const endHour = timeOfDay(String(prefs?.workday_end || "17:00"));
  const slots = planWork(
    (tasks || []).map((t) => ({
      id: t.id,
      title: t.title,
      dueAt: t.due_at,
      priority: t.priority,
      minutes: t.estimated_minutes || 60,
    })),
    [
      ...(events || []).map((e) => ({
        start: new Date(e.starts_at),
        end: new Date(e.ends_at),
      })),
      ...(sessions || []).map((s) => ({
        start: new Date(s.starts_at),
        end: new Date(s.ends_at),
      })),
    ],
    new Date(),
    addDays(new Date(), 8),
    startHour,
    endHour,
    prefs?.timezone || "UTC",
  );
  let explanation =
    "Plan generated by Daymark’s on-device scheduling rules. Sessions are split into focused blocks, fit around existing events, and ordered by deadline and priority.";
  let provider = "deterministic";
  if (process.env.AI_BASE_URL && process.env.AI_MODEL) {
    try {
      const response = await fetch(
        `${process.env.AI_BASE_URL.replace(/\/$/, "")}/chat/completions`,
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            ...(process.env.AI_API_KEY
              ? { Authorization: `Bearer ${process.env.AI_API_KEY}` }
              : {}),
          },
          body: JSON.stringify({
            model: process.env.AI_MODEL,
            temperature: 0.2,
            messages: [
              {
                role: "system",
                content:
                  "You are Daymark, a concise scheduling assistant. Explain the proposed sessions only. Never invent commitments, modify data, or claim changes have been made. The user must approve the provided schedule before it is saved.",
              },
              {
                role: "user",
                content: JSON.stringify({
                  request:
                    body.data.prompt || "Make a realistic plan for this week.",
                  timezone: prefs?.timezone,
                  tasks: (tasks || []).map((t) => ({
                    title: t.title,
                    due_at: t.due_at,
                    priority: t.priority,
                    minutes: t.estimated_minutes || 60,
                  })),
                  busy: events || [],
                  proposed: slots.map((s) => ({
                    title: s.title,
                    start: s.start.toISOString(),
                    end: s.end.toISOString(),
                  })),
                }),
              },
            ],
          }),
        },
      );
      if (!response.ok)
        throw new Error(`AI provider returned ${response.status}`);
      const json = await response.json();
      explanation = json.choices?.[0]?.message?.content || explanation;
      provider = "openai-compatible";
    } catch {
      provider = "deterministic";
      explanation +=
        " The configured AI endpoint was unavailable, so this proposal uses deterministic scheduling.";
    }
  }
  return NextResponse.json({
    slots: slots.map((s) => ({
      taskId: s.taskId,
      title: s.title,
      start: s.start.toISOString(),
      end: s.end.toISOString(),
    })),
    explanation,
    provider,
  });
}
